"""Calculate profit and the share of revenue kept as profit."""

revenue = 200.0
cost = 150.0
profit = revenue - cost
profit_margin = profit / revenue * 100

print(f"Revenue: {revenue:.2f} TRY")
print(f"Cost: {cost:.2f} TRY")
print(f"Profit: {profit:.2f} TRY")
print(f"Profit margin: {profit_margin:.1f}%")
